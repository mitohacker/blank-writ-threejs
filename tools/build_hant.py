"""Builds the Traditional Chinese (繁體) text of Blank Writ from the Simplified tables, with OpenCC (s2tw: phrase-aware character conversion with Taiwan variants, no software-vocabulary rewriting) and a short list of
Taiwan interface words.

    python tools/build_hant.py            (needs: pip install opencc-python-reimplemented)

  data/i18n/zh_*.json            Simplified {English: Chinese} tables (copied from the Godot project by build_assets.py)
  -> data/i18n/hant/zh_*.json    the same keys, Traditional values, converted phrase by phrase (accurate: "头发" -> 頭髮, "里面" -> 裡面)
  -> src/sim/hant_data.js        what the browser needs to convert the rest at run time (names in the data's `zh` fields, a few strings
                                 written in the code): a per-character map for every character of that vocabulary, plus an exact-string
                                 table for the strings where the phrase-level result differs from the character-level one.
  -> data/manifest.json          gains "i18n_hant": the names of the Traditional tables

The game keeps Simplified as the source and converts on demand, so a new Simplified line only needs this script re-run.
"""
from __future__ import annotations

import glob
import json
import re
import sys
from pathlib import Path

import opencc

HERE = Path(__file__).resolve().parent.parent
CJK = re.compile(r"[一-鿿]")
QUOTED = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'')

for _s in (sys.stdout, sys.stderr):
	if hasattr(_s, "reconfigure"):
		_s.reconfigure(encoding="utf-8", errors="replace")


# a few words the Taiwan interface says differently (applied to the Traditional output)
TAIWAN_WORDS = [("設置", "設定"), ("菜單", "選單"), ("幾率", "機率"), ("保存並", "儲存並"), ("立即保存", "立即儲存"), ("揹包", "背包")]


def main() -> int:
	base = opencc.OpenCC("s2tw")
	char_cc = base

	def phrase_convert(v: str) -> str:
		t = base.convert(v)
		for a, b in TAIWAN_WORDS:
			t = t.replace(a, b)
		return t

	class _P:
		convert = staticmethod(phrase_convert)

	phrase = _P()

	# 1. the tables
	out_dir = HERE / "data" / "i18n" / "hant"
	out_dir.mkdir(parents=True, exist_ok=True)
	n_tab = 0
	n_changed = 0
	for f in sorted(glob.glob(str(HERE / "data" / "i18n" / "zh*.json"))):
		src = json.loads(Path(f).read_text(encoding="utf-8"))
		dst = {}
		for k, v in src.items():
			t = phrase.convert(v)
			dst[k] = t
			n_tab += 1
			if t != v:
				n_changed += 1
		(out_dir / Path(f).name).write_text(json.dumps(dst, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")
	print(f"tables: {n_tab} lines, {n_changed} differ from Simplified")

	# 2. the run-time vocabulary: the data's zh fields and the Chinese written in the code
	vocab: set[str] = set()

	def walk(o):
		if isinstance(o, dict):
			for k, v in o.items():
				if k == "zh" and isinstance(v, str) and CJK.search(v):
					vocab.add(v)
				else:
					walk(v)
		elif isinstance(o, list):
			for v in o:
				walk(v)

	for f in list(glob.glob(str(HERE / "data" / "*.json"))) + list(glob.glob(str(HERE / "data" / "events" / "*.json"))):
		walk(json.loads(Path(f).read_text(encoding="utf-8")))
	for f in glob.glob(str(HERE / "src" / "**" / "*.js"), recursive=True):
		if f.endswith("hant_data.js"):
			continue
		for line in Path(f).read_text(encoding="utf-8").split("\n"):
			s = line.strip()
			if s.startswith("//") or s.startswith("*") or s.startswith("/*"):
				continue
			for m in QUOTED.finditer(line):
				lit = m.group(1) if m.group(1) is not None else m.group(2)
				if lit and CJK.search(lit):
					vocab.add(lit)
	# every character of the tables too, so a name that is also a table string converts the same way
	chars: set[str] = set()
	for s in vocab:
		chars.update(c for c in s if CJK.search(c))
	for f in glob.glob(str(HERE / "data" / "i18n" / "zh*.json")):
		for v in json.loads(Path(f).read_text(encoding="utf-8")).values():
			chars.update(c for c in v if CJK.search(c))

	cmap = {}
	for c in sorted(chars):
		t = char_cc.convert(c)
		if t != c and len(t) == 1:
			cmap[c] = t

	def by_char(s: str) -> str:
		return "".join(cmap.get(c, c) for c in s)

	exc = {}
	for s in sorted(vocab):
		t = phrase.convert(s)
		if t != by_char(s):
			exc[s] = t

	src_chars = "".join(cmap.keys())
	dst_chars = "".join(cmap.values())
	js = (
		"// GENERATED by tools/build_hant.py (OpenCC s2tw) - do not edit.\n"
		"// The Simplified -> Traditional vocabulary of the names and the few strings written in the code; the story and interface\n"
		"// text is converted ahead of time into data/i18n/hant/.\n"
		f"export const SRC = {json.dumps(src_chars, ensure_ascii=False)};\n"
		f"export const DST = {json.dumps(dst_chars, ensure_ascii=False)};\n"
		f"export const EXC = {json.dumps(exc, ensure_ascii=False, indent=1)};\n"
	)
	(HERE / "src" / "sim" / "hant_data.js").write_text(js, encoding="utf-8", newline="\n")
	print(f"vocabulary: {len(vocab)} strings, {len(cmap)} characters change, {len(exc)} exact-string exceptions")

	# 3. the manifest
	mp = HERE / "data" / "manifest.json"
	man = json.loads(mp.read_text(encoding="utf-8"))
	man["i18n"] = sorted(p.name for p in (HERE / "data" / "i18n").glob("zh*.json"))   # includes the web build's own zh_web.json
	man["i18n_hant"] = sorted(p.name for p in out_dir.glob("zh*.json"))
	mp.write_text(json.dumps(man, indent=1), encoding="utf-8", newline="\n")
	return 0


sys.exit(main())
